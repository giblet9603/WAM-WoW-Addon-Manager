# theme name -> (box title, [art, biggest first])
CRESTS: dict[str, tuple[str, list[str]]] = {
    "wow": ("World of Warcraft", [WOW_LARGE, WOW_COMPACT]),
    "horde": ("For the Horde!", [HORDE_LARGE, HORDE_COMPACT]),
    "alliance": ("For the Alliance!", [ALLIANCE_LARGE, ALLIANCE_COMPACT]),
}

# Rows that must stay free for the addon details above the crest.
MIN_DETAIL_ROWS = 10


def size_of(art: str) -> tuple[int, int]:
    """(columns, rows) the art takes up inside its box, including the box's border and padding."""
    lines = art.splitlines()
    return max(len(line) for line in lines) + 4, len(lines) + 2


def pick(theme: str | None, width: int, height: int) -> tuple[str, str] | None:
    """(title, art) for the biggest crest that fits a column of this size, or None to show nothing."""
    entry = CRESTS.get(theme or "")
    if entry is None:
        return None
    title, options = entry
    for art in options:
        need_w, need_h = size_of(art)
        if width >= need_w and height - need_h >= MIN_DETAIL_ROWS:
            return title, art
    return None
